class Solution {
public:
    long long countCommas(long long n) {
       if(n < 999){ return 0; } if(n < 1000000){ return n-999; } if(n < 1000000000){return 999999-999+ 2*(n-999999);  }   if(n < 1000000000000){ return 999999-999 + 2*(999999999-999999) + 3*(n-999999999);
        }  if(n == 1000000000000000){   return 999999-999+2*(999999999-999999)+3*(999999999999-999999999)+      4*(n-999999999999) + 1; }return 999999-999+2*(999999999-999999)+3*(999999999999-999999999)+       4*(n-999999999999);}
};